import test from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { readFileSync } from 'node:fs';
import { spawn } from 'node:child_process';
import path from 'node:path';
import { migrate } from '../local/migrate.mjs';
import { migrateCatalog } from '../local/catalog-model.mjs';
import { seedCatalog } from '../local/catalog-seed.mjs';
import { makeTestDirectory, freePort, stopServer } from './helpers/runtime.mjs';
import { validJpegBase64 } from './helpers/valid-jpeg.mjs';
import { ownerWorkspaceView } from '../web/shop-workspace-view.mjs';

test('complete owner lifecycle through Vercel entrypoints separates dashboard access, approval and public visibility', async t => {
  const dir = makeTestDirectory(path.resolve('.local/shop-lifecycle-'));
  const db = new DatabaseSync(path.join(dir, 'stock.sqlite')); t.after(() => db.close());
  db.exec(readFileSync('local/schema.sql', 'utf8')); migrate(db);
  db.prepare("INSERT INTO categories(id,name) VALUES ('generic','Generic')").run();
  for (const [id, storage, price] of [['life-v1', '128 GB', 1000], ['life-v2', '256 GB', 1200]]) db.prepare('INSERT INTO products(id,brand,model,name,category_id,specs,reference_price,reference_currency) VALUES (?,?,?,?,?,?,?,?)').run(id, 'Lifecycle', 'Widget', 'Lifecycle Widget', 'generic', JSON.stringify({ supplied_specs: { storage }, slug: id }), price, 'INR');
  db.prepare("INSERT INTO shops(id,name,area,city,status) VALUES ('existing','Existing fixture shop','Fixture area','Jammu','active')").run();
  migrateCatalog(db, { apply: true }); seedCatalog(db, { apply: true });
  const model = db.prepare('SELECT id,slug FROM catalog_products LIMIT 1').get();
  const originalShop = JSON.stringify(db.prepare("SELECT * FROM shops WHERE id='existing'").get());
  const originalOffers = JSON.stringify(db.prepare("SELECT * FROM offers WHERE shop_id='existing' ORDER BY id").all());
  const port = await freePort(), base = 'http://127.0.0.1:' + port;
  let proc;
  async function start() {
    proc = spawn(process.execPath, ['tests/helpers/vercel-function-process.mjs'], { env: { ...process.env, LOCAL_DATA_DIR: dir, PORT: String(port), VERCEL: '0', NEARBY_DATABASE: 'sqlite', IMAGE_STORAGE: 'mock-cloudinary', OWNER_AUTO_APPROVAL: '1', SEED_SAMPLE_DATA: '0', COOKIE_SECURE: '0' }, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe', 'ipc'] });
    await new Promise((resolve, reject) => { let output = ''; const timer = setTimeout(() => reject(Error(output)), 12000); proc.stdout.on('data', c => { output += c; if (output.includes('harness ready')) { clearTimeout(timer); resolve(); } }); proc.stderr.on('data', c => { output += c; }); proc.once('error', reject); });
  }
  t.after(() => proc ? stopServer(proc) : undefined); await start();
  async function call(route, body, cookie = '') {
    const res = await fetch(base + '/api/' + route, { ...(body ? { method: 'POST', body: JSON.stringify(body) } : {}), headers: { Origin: base, 'Content-Type': 'application/json', Cookie: cookie } });
    return { status: res.status, data: await res.json(), cookie: res.headers.get('set-cookie')?.split(';')[0] };
  }
  const owner = await call('auth/signup', { email: 'owner@lifecycle.invalid', password: 'owner-lifecycle-password' });
  assert.equal(owner.status, 200); assert.equal((await call('owner', null, owner.cookie)).status, 200);
  assert.equal((await call('shop/catalog', null, owner.cookie)).data.shops.length, 0);
  const login = await call('auth/login', { email: 'owner@lifecycle.invalid', password: 'owner-lifecycle-password' }); assert.equal(login.status, 200);
  const submitted = { name: 'Lifecycle Fixture Shop', address: 'Synthetic fixture address', area: 'Fixture area', pincode: '180001', categories: ['generic'] };
  assert.equal((await call('shops', { ...submitted, status: 'active' }, owner.cookie)).status, 403);
  const registered = await call('shops', submitted, owner.cookie); assert.equal(registered.status, 200, JSON.stringify(registered.data));
  const shop = registered.data.shop, shopId = shop.id; assert.equal(shop.status, 'pending');
  assert.equal((await call('session', null, owner.cookie)).data.ownerAutoApproval, false);
  let workspace = (await call('shop/catalog', null, owner.cookie)).data;
  assert.equal(workspace.shops[0].status, 'pending'); assert.equal(workspace.offers.length, 0);
  assert.equal((await call('shop/variants?shop=' + shopId + '&product=' + model.id, null, owner.cookie)).data.variants.length, 2);
  const other = await call('auth/signup', { email: 'other@lifecycle.invalid', password: 'other-lifecycle-password' });
  const offer = { shop_id: shopId, variant_id: 'life-v1', price: 990, stock_status: 'available', shop_product_url: '' };
  assert.equal((await call('shop/offer', offer, other.cookie)).status, 403);
  assert.equal((await call('shop-details', { shop_id: shopId, name: 'Unauthorized' }, other.cookie)).status, 403);
  assert.equal((await call('shop/variants?shop=' + shopId + '&product=' + model.id, null, other.cookie)).status, 403);
  for (const field of ['status', 'approval_status', 'verification_status', 'owner_id', 'deleted_at']) assert.equal((await call('shop-details', { shop_id: shopId, [field]: 'active' }, owner.cookie)).status, 403);
  const invalid = await call('shop-details', { shop_id: shopId, name: 'Must not save', categories: ['missing'] }, owner.cookie); assert.equal(invalid.status, 400);
  assert.equal(db.prepare('SELECT name FROM shops WHERE id=?').get(shopId).name, submitted.name);
  const image = await call('upload', { image: 'data:image/jpeg;base64,' + validJpegBase64 }, owner.cookie); assert.equal(image.status, 200);
  assert.equal((await call('shop-details', { shop_id: shopId, name: 'Updated Fixture Shop', address: 'Corrected fixture address', categories: [], open: '09:00', close: '18:00', photos: [image.data.url] }, owner.cookie)).status, 200);
  assert.equal((await call('shop-details', { shop_id: shopId, lat: 32.7 }, owner.cookie)).status, 400);
  const saved = await call('shop/offer', offer, owner.cookie); assert.equal(saved.status, 200, JSON.stringify(saved.data));
  assert.equal((await call('shop/import', { shop_id: shopId, csv: 'variant_id,price,stock_status,shop_product_url\nlife-v1,980,low_stock,\nlife-v2,1190,out_of_stock,' }, owner.cookie)).status, 200);
  assert.equal((await call('shop/history?offer=' + saved.data.id, null, other.cookie)).status, 403);
  assert.equal((await call('shop/history?offer=' + saved.data.id, null, owner.cookie)).data.history.length, 2);
  assert.equal((await fetch(base + '/api/shop/offers.csv?shop=' + shopId, { headers: { Cookie: owner.cookie } })).status, 200);
  assert.equal((await fetch(base + '/api/shop/offers.csv?shop=' + shopId, { headers: { Cookie: other.cookie } })).status, 403);
  assert.equal((await call('listings', { shop_id: shopId, product_id: 'life-v1', price_min: 980, currency: 'INR', status_reported: 'in_stock' }, owner.cookie)).status, 200);
  async function visible(expected) {
    assert.equal((await call('shops')).data.shops.some(s => s.id === shopId), expected, 'directory');
    assert.equal((await call('search?q=Lifecycle%20Widget')).data.listings.some(l => l.shop_id === shopId), expected, 'confirmed search');
    assert.equal((await call('shops/' + shopId)).status, expected ? 200 : 404, 'shop API');
    assert.equal((await fetch(base + '/shops/' + shopId)).status, expected ? 200 : 404, 'shop page');
    assert.equal((await call('catalog-shops/' + shopId)).status, expected ? 200 : 404, 'grouped shop catalogue');
    assert.equal((await call('models/' + model.id)).data.offers.some(o => o.shop_id === shopId), expected, 'model comparisons');
    assert.equal((await call('models?shop=' + shopId)).data.models.length > 0, expected, 'shop-specific model listing');
  }
  await visible(false);
  workspace = (await call('shop/catalog', null, owner.cookie)).data;
  assert.equal(workspace.offers.length, 2); assert.ok(workspace.offers.every(o => o.price_rank === 'Not publicly listed'));
  const inventoryBefore = JSON.stringify(db.prepare('SELECT * FROM offers WHERE shop_id=? ORDER BY id').all(shopId));
  const setup = JSON.parse(readFileSync(path.join(dir, 'security.json'), 'utf8'));
  const adminCredentials = { email: 'admin@lifecycle.invalid', password: 'admin-lifecycle-password' };
  assert.equal((await call('admin/setup', { ...adminCredentials, token: setup.setupToken })).status, 200);
  const admin = (await call('admin/login', adminCredentials)).cookie;
  assert.equal((await call('admin/shop-status', { id: shopId, status: 'active' }, owner.cookie)).status, 401);
  assert.equal((await call('shop/catalog', null, admin)).status, 401);
  assert.equal((await call('admin/shop-status', { id: shopId, status: 'active' }, admin)).status, 200);
  assert.equal((await call('shop/status?shop=' + shopId, null, owner.cookie)).data.shop.status, 'active');
  assert.equal(db.prepare('SELECT verification_status FROM shops WHERE id=?').get(shopId).verification_status, 'unverified');
  await visible(true);
  assert.equal(JSON.stringify(db.prepare('SELECT * FROM offers WHERE shop_id=? ORDER BY id').all(shopId)), inventoryBefore);
  assert.equal((await call('admin/shop-status', { id: shopId, status: 'rejected', reason: 'Correct the shop address.' }, admin)).status, 200);
  await visible(false);
  const rejected = (await call('shop/status?shop=' + shopId, null, owner.cookie)).data.shop;
  assert.equal(rejected.rejection_reason, 'Correct the shop address.');
  assert.equal((await call('shop-details', { shop_id: shopId, address: 'Corrected again' }, owner.cookie)).status, 200);
  assert.equal((await call('shop/offer', { ...offer, price: 970 }, owner.cookie)).status, 200);
  assert.equal((await call('shop-resubmit', { shop_id: shopId }, other.cookie)).status, 403);
  assert.equal((await call('shop-resubmit', { shop_id: shopId }, owner.cookie)).data.shop.status, 'pending');
  assert.equal((await call('shop-resubmit', { shop_id: shopId }, owner.cookie)).status, 409);
  await visible(false);
  assert.equal((await call('admin/shop-status', { id: shopId, status: 'on_hold' }, admin)).status, 200);
  assert.equal((await call('shop/catalog', null, owner.cookie)).data.offers.length, 2);
  assert.equal((await call('shop-details', { shop_id: shopId, name: 'Blocked' }, owner.cookie)).status, 403);
  assert.equal((await call('shop/offer', offer, owner.cookie)).status, 403);
  assert.equal((await call('confirm', { shop_id: shopId }, owner.cookie)).status, 403);
  assert.equal((await call('shop-resubmit', { shop_id: shopId }, owner.cookie)).status, 403);
  assert.equal((await call('admin/shop-status', { id: shopId, status: 'active' }, admin)).status, 200);
  await stopServer(proc); await start();
  assert.equal((await call('session', null, owner.cookie)).data.user.email, 'owner@lifecycle.invalid');
  assert.equal((await call('shop/status?shop=' + shopId, null, owner.cookie)).data.shop.status, 'active');
  assert.equal((await call('shop/catalog', null, owner.cookie)).data.offers.find(o => o.variant_id === 'life-v1').price, 970);
  assert.equal((await fetch(base + image.data.url)).status, 200);
  await visible(true);
  assert.equal(JSON.stringify(db.prepare("SELECT * FROM shops WHERE id='existing'").get()), originalShop);
  assert.equal(JSON.stringify(db.prepare("SELECT * FROM offers WHERE shop_id='existing' ORDER BY id").all()), originalOffers);
  assert.equal(db.prepare('PRAGMA foreign_key_check').all().length, 0);
});

test('owner dashboard exposes registration, preapproval editing, rejection recovery and safe approval labels', () => {
  const data = { shops: [], offers: [], models: [], categories: [{ id: 'generic', name: 'Generic' }] };
  assert.match(ownerWorkspaceView(data, { shopId: '' }), /id="shop-model-register"/);
  const shop = { id: 's', name: 'Fixture Shop', status: 'pending', categories: '[]', photos: '[]' }; data.shops = [shop];
  let html = ownerWorkspaceView(data, { shopId: 's' });
  for (const text of ['Pending approval', 'shop-model-details', 'shop-model-add-offer', 'shop-model-import', 'shop-model-request', 'hidden from public discovery']) assert.ok(html.includes(text), text);
  shop.status = 'rejected'; shop.rejection_reason = '<script>bad</script>';
  html = ownerWorkspaceView(data, { shopId: 's' });
  assert.match(html, /data-shop-resubmit/); assert.match(html, /&lt;script&gt;/); assert.doesNotMatch(html, /<script>/);
  shop.status = 'active'; shop.rejection_reason = null; html = ownerWorkspaceView(data, { shopId: 's' });
  assert.match(html, />Approved</); assert.doesNotMatch(html, />Verified</);
  shop.status = 'on_hold'; html = ownerWorkspaceView(data, { shopId: 's' });
  assert.match(html, /On hold/); assert.doesNotMatch(html, /id="shop-model-add-offer"|id="shop-model-details"|data-shop-resubmit/);
});
